"""B13. Out-of-sample check of the static-margin calibration SM_Euler = a + b * SM_VLM (fitted by b4_calibrate.py on 20 designs).
Twelve run champions that were not in the fit (results_v3/cfd_oos/) were solved with the same Euler setup; this script compares the
Euler value with the prediction of the frozen calibration. It does not refit anything. SM_Euler = -dCMy/dCL between two angles of attack.
Writes results_v3/cfd_oos/oos_validation.{csv,json}, paper_v2/numbers_oos.tex, paper_v2/tables/tab_oos.tex.
usage: python3 b13_oos_validate.py"""
import glob, json, os
import numpy as np, pandas as pd
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", "..", ".."))
V3 = f"{ROOT}/revision_runs/results_v3"; P = f"{ROOT}/research/paper_b_flagship/revision/paper_v2"
cal = json.load(open(f"{V3}/cfd_calibration/calibration.json")); a, b, sd = cal["a"], cal["b"], cal["resid_sd"]
sel = pd.read_csv(f"{V3}/cfd_oos/cfd_selection.csv").set_index("name")
ARM = {"turbo": "TuRBO", "alr": "AL-R", "adapt": "adapt10"}
rows = []
for f in sorted(glob.glob(f"{V3}/cfd_oos/*_h7/result.csv")):
    d = pd.read_csv(f).sort_values("alpha"); assert len(d) == 2, f
    a0, a1 = d.iloc[0], d.iloc[1]; name = a0.design
    sme = -(a1.CMy - a0.CMy) / (a1.CL - a0.CL); pred = a + b * a0.VLM_SM
    assert abs(a0.VLM_SM - sel.loc[name, "SM_vlm"]) < 1e-6
    key = "".join(c for c in name.split("_")[1] if c.isalpha()); seed = int("".join(c for c in name if c.isdigit()))
    rows.append(dict(design=name, arm=ARM[key], seed=seed, SM_vlm=a0.VLM_SM, SM_pred=pred, SM_euler=sme, err=sme - pred,
                     CL_ratio=a0.CL / a0.VLM_CL_cruise, worst_log10_rho=d.final_log10_rho.max(), nodes=int(a0.nodes),
                     pred_over_cap=bool(pred > 0.25), euler_over_cap=bool(sme > 0.25)))
T = pd.DataFrame(rows).sort_values("SM_vlm").reset_index(drop=True); T.to_csv(f"{V3}/cfd_oos/oos_validation.csv", index=False)
e = T.err.values; n = len(T)
S = dict(n=n, a=a, b=b, fit_resid_sd=sd, mean_err=e.mean(), rmse=float(np.sqrt((e ** 2).mean())), mae=float(np.abs(e).mean()), max_abs_err=float(np.abs(e).max()),
         sm_vlm_min=T.SM_vlm.min(), sm_vlm_max=T.SM_vlm.max(), sm_euler_min=T.SM_euler.min(), sm_euler_max=T.SM_euler.max(),
         n_pred_over_cap=int(T.pred_over_cap.sum()), n_euler_over_cap=int(T.euler_over_cap.sum()), n_class_agree=int((T.pred_over_cap == T.euler_over_cap).sum()),
         r2_pred=float(1 - (e ** 2).sum() / ((T.SM_euler - T.SM_euler.mean()) ** 2).sum()), CL_ratio_min=T.CL_ratio.min(), CL_ratio_max=T.CL_ratio.max(),
         worst_log10_rho=T.worst_log10_rho.max())
json.dump(S, open(f"{V3}/cfd_oos/oos_validation.json", "w"), indent=1, default=float)
m = lambda k, v: f"\\newcommand{{\\Noos{k}}}{{{v}}}\n"
with open(f"{P}/numbers_oos.tex", "w") as g:
    g.write("% generated by revision_runs/results_v3/scripts/b13_oos_validate.py; do not edit\n")
    g.write(m("N", n) + m("Rmse", f"{S['rmse']:.3f}") + m("Mae", f"{S['mae']:.3f}") + m("Max", f"{S['max_abs_err']:.3f}") + m("Bias", f"{S['mean_err']:+.3f}".replace("-", "$-$").replace("+", "$+$"))
            + m("FitSd", f"{sd:.3f}") + m("VlmLo", f"{S['sm_vlm_min']:.3f}") + m("VlmHi", f"{S['sm_vlm_max']:.3f}") + m("EulerLo", f"{S['sm_euler_min']:.3f}") + m("EulerHi", f"{S['sm_euler_max']:.3f}")
            + m("PredOver", S["n_pred_over_cap"]) + m("EulerOver", S["n_euler_over_cap"]) + m("Agree", S["n_class_agree"]) + m("RsqPred", f"{S['r2_pred']:.3f}")
            + m("NearCap", f"{T[T.pred_over_cap & ~T.euler_over_cap].SM_euler.max():.4f}") + m("ClLo", f"{S['CL_ratio_min']:.3f}") + m("ClHi", f"{S['CL_ratio_max']:.3f}"))
with open(f"{P}/tables/tab_oos.tex", "w") as g:
    g.write("% generated by b13_oos_validate.py; do not edit\n\\begin{tabular}{llrrrr}\n\\toprule\nStrategy & Seed & Lattice $\\mathrm{SM}$ & Predicted Euler $\\mathrm{SM}$ & Euler $\\mathrm{SM}$ & Error \\\\\n\\midrule\n")
    for r in T.itertuples():
        g.write(f"{r.arm} & {r.seed} & {r.SM_vlm:.3f} & {r.SM_pred:.3f} & {r.SM_euler:.3f} & ${r.err:+.3f}$ \\\\\n")
    g.write(f"\\midrule\n\\multicolumn{{5}}{{l}}{{Root-mean-square error}} & {S['rmse']:.3f} \\\\\n\\multicolumn{{5}}{{l}}{{Largest absolute error}} & {S['max_abs_err']:.3f} \\\\\n\\bottomrule\n\\end{{tabular}}\n")
print(T.round(4).to_string()); print({k: (round(v, 4) if isinstance(v, float) else v) for k, v in S.items()})
