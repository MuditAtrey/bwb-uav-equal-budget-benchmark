"""Double-budget runs (B15, 2026-11-17) and intermediate-budget summary. TuRBO and adapt10 seeds 0-9 and AL-R seeds 0-4 were continued from 287 to
574 evaluations (results_v3/long_budget; the first 287 rows are the benchmark runs). Writes numbers_long.tex (\\Nl*) and tables/tab_long.tex.
Outcome = best feasible range so far, pool included. usage: python3 make_numbers_long.py"""
import glob, os, re
import numpy as np, pandas as pd
from scipy import stats
HERE = os.path.dirname(os.path.abspath(__file__)); REPO = os.path.abspath(f"{HERE}/../../../.."); V3 = f"{REPO}/revision_runs/results_v3"; R = f"{REPO}/revision_runs/results_revision"
F = (48 * 5.0 * 3.6 * 0.80 / 3.400) / 160.0
db = pd.read_csv(f"{REPO}/flying_wing_optimizer/results/database.csv", low_memory=False); p1 = db[db.evaluation_type.str.startswith("Phase1") & db.is_valid.astype(bool)]; POOL = p1.range_calm_km.max() * F
key = lambda s: int(re.findall(r"seed(\d+)", s)[-1])
def at(pats, rc, n, need):
    out = []
    for f in sorted(sum((glob.glob(p) for p in pats), []), key=key):
        d = pd.read_csv(f)
        if len(d) < need and "al_seed16" not in f: continue
        d = d.iloc[:n]; v = d[d.is_valid.astype(bool)]; out.append(max(v[rc].max() * F if len(v) else 0.0, POOL))
    return np.array(out)
pf = lambda p: "<0.001" if p < 0.001 else f"{p:.3f}"; w = lambda a, b: float(stats.ttest_ind(a, b, equal_var=False).pvalue)
M = []; mac = lambda k, v: M.append(f"\\newcommand{{\\Nl{k}}}{{{v}}}")
L = {"Turbo": ([f"{V3}/long_budget/turbo/turbo_seed*.csv"], "range_km"), "Adapt": ([f"{V3}/long_budget/adapt/adapt10_seed*.csv"], "range_km"), "ALR": ([f"{V3}/long_budget/alr/al_seed*.csv"], "range_calm_km")}
B = [287, 400, 574]; X = {(a, n): at(p, rc, n, 574) for a, (p, rc) in L.items() for n in B}
assert len(X[("Turbo", 574)]) == 10 and len(X[("Adapt", 574)]) == 10 and len(X[("ALR", 574)]) == 5
T = ["% generated by make_numbers_long.py; do not edit", "\\begin{tabular*}{\\linewidth}{@{\\extracolsep{\\fill}}lrrr@{}}", "\\toprule", "Evaluations beyond the pool & 287 & 400 & 574 \\\\", "\\midrule"]
NAME = {"Turbo": "TuRBO", "Adapt": "adapt10", "ALR": "AL-R"}
for a in ("Turbo", "ALR", "Adapt"):
    T.append(f"{NAME[a]} ($n={len(X[(a, 574)])}$) & " + " & ".join(f"{X[(a, n)].mean():.1f} $\\pm$ {X[(a, n)].std(ddof=1):.1f}" for n in B) + " \\\\")
    for n, tag in zip(B, ["A", "B", "C"]): mac(f"{a}{tag}Mean", f"{X[(a, n)].mean():.1f}"); mac(f"{a}{tag}Sd", f"{X[(a, n)].std(ddof=1):.1f}")
    mac(f"{a}Gain", f"{X[(a, 574)].mean() - X[(a, 287)].mean():.1f}")
T.append("\\midrule")
def diff(lab, fa, fb, k):
    cells = []
    for n, tag in zip(B, ["A", "B", "C"]):
        a_, b_ = fa(n), fb(n); p = w(a_, b_); cells.append(f"${a_.mean() - b_.mean():+.1f}$ ({pf(p).replace('<', '$<$')})"); mac(f"{k}{tag}D", f"{a_.mean() - b_.mean():.1f}"); mac(f"{k}{tag}P", pf(p))
    T.append(f"{lab}, km (Welch $p$) & " + " & ".join(cells) + " \\\\")
diff("TuRBO minus adapt10", lambda n: X[("Turbo", n)], lambda n: X[("Adapt", n)], "TvA")
diff("TuRBO minus AL-R, seeds 0 to 4", lambda n: X[("Turbo", n)][:5], lambda n: X[("ALR", n)], "TvR")
diff("AL-R minus adapt10, seeds 0 to 4", lambda n: X[("ALR", n)], lambda n: X[("Adapt", n)][:5], "RvA")
T += ["\\bottomrule", "\\end{tabular*}"]; open(f"{HERE}/tables/tab_long.tex", "w").write("\n".join(T) + "\n")
mac("TurboMax", f"{X[('Turbo', 574)].max():.1f}"); mac("Budget", "574"); mac("AllMax", f"{max(X[(a, 574)].max() for a in L):.1f}")
# intermediate budgets of the main benchmark (all seeds), for the sentence that accompanies the supplementary table
A = {"Turbo": ([f"{V3}/turbo_fix/turbo_seed*.csv", f"{V3}/turbo_fix_extra/turbo_seed*.csv"], "range_km"), "ALR": ([f"{V3}/al_repair/al_seed*.csv", f"{V3}/al_repair_extra/al_seed*.csv"], "range_calm_km"),
     "Adapt": ([f"{V3}/adapt_fix/adapt10_seed*.csv"], "range_km")}
BB = [50, 100, 150, 200, 287]; Y = {(a, n): at(p, rc, n, 287) for a, (p, rc) in A.items() for n in BB}
dTR = [Y[("Turbo", n)].mean() - Y[("ALR", n)].mean() for n in BB]; pTR = [w(Y[("Turbo", n)], Y[("ALR", n)]) for n in BB]; pRA = [w(Y[("ALR", n)], Y[("Adapt", n)]) for n in BB]
mac("AnyTRlo", f"{min(dTR):.1f}"); mac("AnyTRhi", f"{max(dTR):.1f}"); mac("AnyTRsigFrom", str(next(n for n, p in zip(BB, pTR) if all(q < 0.05 for q in pTR[BB.index(n):])))); mac("AnyRApmax", pf(max(pRA)))
open(f"{HERE}/numbers_long.tex", "w").write("% generated by make_numbers_long.py; do not edit\n" + "\n".join(M) + "\n"); print("\n".join(T)); print(dTR, pTR, pRA)
